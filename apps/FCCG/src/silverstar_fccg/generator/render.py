def _StringCrc32_Get(value: str) -> int:
    return zlib.crc32(value.encode("utf-8")) & 0xFFFFFFFF


def _CapabilityRoutesSource_Render(
    model: ProjectModel, catalog: PluginCatalog
) -> str:
    resolution = CapabilityResolution_Resolve(model, catalog)
    if not resolution.valid:
        raise ValueError("Cannot generate unresolved capability routes")
    rows = ",\n".join(
        "    {"
        f"0x{_StringCrc32_Get(route.requirement.capability):08X}UL, "
        f"0x{_StringCrc32_Get(route.provider.instance_id):08X}UL, "
        f"0x{_StringCrc32_Get(route.provider.plugin):08X}UL, "
        f"0x{_StringCrc32_Get(route.requirement.consumer_component):08X}UL, "
        f"0x{_StringCrc32_Get(route.requirement.purpose):08X}UL, "
        f"{1 if route.automatic else 0}U}}"
        for route in resolution.routes
    )
    if not rows:
        rows = "    {0UL, 0UL, 0UL, 0UL, 0UL, 1U}"
    return f"""#include "project_capability_routes.h"

{AUTOGEN_C_COMMENT}

#include <stddef.h>

static const ProjectCapabilityRoute s_project_capability_routes[] =
{{
{rows}
}};

uint16_t ProjectCapabilityRoute_CountGet(void)
{{
    return {len(resolution.routes)}U;
}}

ProjectCapabilityRouteResult ProjectCapabilityRoute_Get(
    uint16_t index, ProjectCapabilityRoute *route)
{{
    if ((route == NULL) ||
        (index >= ProjectCapabilityRoute_CountGet()))
    {{
        return PROJECT_CAPABILITY_ROUTE_INVALID_ARGUMENT;
    }}
    *route = s_project_capability_routes[index];
    return PROJECT_CAPABILITY_ROUTE_OK;
}}
"""


