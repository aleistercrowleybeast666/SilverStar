def _GoldenExpected_Render(
    model: ProjectModel, decoder_profile: LogDecoderPackageResult
) -> str:
    semantics = json.loads(
        decoder_profile.project_semantics_content.decode("utf-8")
    )
    record_catalog = json.loads(
        decoder_profile.record_catalog_content.decode("utf-8")
    )
    included_names = (
        "DECODER_PROFILE_DESCRIPTOR",
        "SYSTEM_CONFIG",
        "DEVICE_DESCRIPTOR",
        "LOG_STREAM_DESCRIPTOR",
        "IMU_CORRECTED",
        "GNSS_NATIVE",
        "BARO_NATIVE",
        "EVENT",
        "STATS",
        "TELEMETRY_DIAG",
        "INERTIAL_INCREMENT",
        "PURE_INS",
        "ESTIMATOR",
    )
    catalog_records = {
        str(record["name"]): record
        for record in record_catalog.get("records", [])
        if isinstance(record, dict) and isinstance(record.get("name"), str)
    }
    if any(name not in catalog_records for name in included_names):
        raise ValueError("Golden Sample Record Catalog is incomplete")
    expected = {
        "schema_id": "silverstar.golden-sslog-expectation/1.0",
        "project": model.identity.name,
        "golden_log": f"{model.identity.name}_golden.sslog",
        "generator": "Tests/Host/generate_golden_sample.c",
        "codec_sources": [
            "Protocol/SSLOG/Src/sslog_protocol.c",
            "Protocol/SSLOG/Src/sslog_records.c",
        ],
        "record_catalog_sha256": decoder_profile.record_catalog_sha256,
        "project_semantics_sha256": decoder_profile.project_semantics_sha256,
        "generation_profile_sha256": decoder_profile.generation_profile_sha256,
        "records": [
            {
                "id": catalog_records[name]["id"],
                "name": name,
                "version": catalog_records[name]["version"],
            }
            for name in included_names
        ],
        "canonical_channels": semantics.get("canonical_channels", []),
        "capability_endpoints": semantics.get("capability_endpoints", []),
    }
    return json.dumps(
        expected,
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
        allow_nan=False,
    ) + "\n"
