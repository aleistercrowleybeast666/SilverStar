def _GeneratedNumber_Render(
    value: float | int, *, value_type: str, scale: float
) -> str:
    scaled = float(value) * scale
    if value_type == "integer" or scale != 1.0:
        integer_value = int(round(scaled))
        if integer_value < 0 or integer_value > 0xFFFFFFFF:
            raise ValueError("Generated integer mode parameter exceeds uint32")
        return f"{integer_value}U"
    rendered = f"{float(value):.9g}"
    if "." not in rendered and "e" not in rendered.casefold():
        rendered += ".0"
    rendered += "f"
    return f"({rendered})" if float(value) < 0.0 else rendered


def _DeviceRuntimeDefaults_Get(
    model: ProjectModel, catalog: PluginCatalog
) -> list[tuple[str, str]]:
    """Resolve fixed device defaults through the same primary descriptor route."""
    catalog = catalog.ProjectView_Get(model)
    result: dict[str, str] = {}
    for entry in _DeviceDescriptorEntries_Get(model, catalog):
        if "SYSTEM_DESCRIPTOR_FLAG_PRIMARY" not in str(entry.get("flags", "")):
            continue
        source_id = str(entry["_source_instance_id"])
        manifest = (
            catalog.InstanceIdComponent_Get(source_id)
            if source_id else catalog.Component_Get(str(entry["_component_id"]))
        )
        declarations = manifest.metadata.get("runtime_defaults", {})
        if not isinstance(declarations, dict):
            raise ValueError(f"Invalid runtime defaults: {manifest.component_id}")
        defaults = declarations.get(str(entry.get("class", "")), {})
        if not isinstance(defaults, dict):
            raise ValueError(f"Invalid device class defaults: {manifest.component_id}")
        for symbol, value in defaults.items():
            if (
                not isinstance(symbol, str)
                or re.fullmatch(r"SYSTEM_[A-Z0-9_]+", symbol) is None
                or not (
                    (type(value) is int and 0 <= value <= 0xFFFFFFFF)
                    or (
                        isinstance(value, str)
                        and re.fullmatch(r"SYSTEM_[A-Z0-9_]+", value) is not None
                    )
                )
            ):
                raise ValueError(f"Invalid device runtime default: {symbol}")
            rendered = f"{value}U" if isinstance(value, int) else value
            if symbol in result and result[symbol] != rendered:
                raise ValueError(f"Conflicting primary device default: {symbol}")
            result[symbol] = rendered
    return sorted(result.items())


def _DeviceBuildCapabilitiesHeader_Render(model: ProjectModel, catalog: PluginCatalog) -> str:
    """Render target facts from the physical provider selected for each class."""
    catalog = catalog.ProjectView_Get(model)
    entries = _DeviceDescriptorEntries_Get(model, catalog)
    providers: dict[str, PluginManifest] = {}
    for entry in entries:
        device_class = str(entry.get("class", ""))
        if device_class not in providers or "SYSTEM_DESCRIPTOR_FLAG_PRIMARY" in str(entry.get("flags", "")):
            source_id = str(entry["_source_instance_id"])
            providers[device_class] = (
                catalog.InstanceIdComponent_Get(source_id)
                if source_id else catalog.Component_Get(str(entry["_component_id"]))
            )
    selected_capabilities = {
        capability for instance in model.device_instances
        for capability in catalog.InstanceComponent_Get(instance).provides
    }
    bindings = catalog.Component_Get(model.mcu).metadata.get("device_build_capabilities", [])
    if not isinstance(bindings, list):
        raise ValueError("Target device build capabilities must be an array")
    definitions: dict[str, str] = {}
    for binding in bindings:
        if not isinstance(binding, dict):
            raise ValueError("Invalid target device build capability")
        symbol = binding.get("symbol", "")
        device_class = binding.get("class", "")
        if not isinstance(symbol, str) or re.fullmatch(r"SYSTEM_SELECTED_[A-Z0-9_]+", symbol) is None:
            raise ValueError("Invalid target device capability symbol")
        if symbol in definitions:
            raise ValueError(f"Duplicate target device capability: {symbol}")
        provider = providers.get(device_class)
        capabilities = selected_capabilities if device_class == "*" else set(provider.provides if provider else ())
        recommendations = {
            value["parameter_id"]: value["value"]
            for value in (provider.metadata.get("sensor_recommendations", []) if provider else [])
            if isinstance(value, dict) and isinstance(value.get("parameter_id"), str)
            and type(value.get("value")) in (int, float) and float(value["value"]) > 0.0
        }
        if "capability" in binding:
            value = "1U" if binding["capability"] in capabilities else "0U"
        elif "recommendation" in binding:
            value = _GeneratedNumber_Render(recommendations.get(binding["recommendation"], 0.0), value_type="float", scale=1.0)
        elif "recommendations" in binding:
            parameters = binding["recommendations"]
            if not isinstance(parameters, list) or not parameters:
                raise ValueError(f"Invalid target recommendation group: {symbol}")
            value = "1U" if all(parameter in recommendations for parameter in parameters) else "0U"
        else:
            raise ValueError(f"Target capability has no declarative source: {symbol}")
        enable_symbol = binding.get("enable_symbol")
        if enable_symbol:
            if not isinstance(enable_symbol, str) or re.fullmatch(r"SYSTEM_USER_[A-Z0-9_]+", enable_symbol) is None:
                raise ValueError(f"Invalid target capability enable symbol: {symbol}")
            value = f"({enable_symbol} * {value})"
        definitions[symbol] = value
    rows = "\n".join(f"#ifndef {symbol}\n#define {symbol} {value}\n#endif" for symbol, value in sorted(definitions.items()))
    return f"""#ifndef __PROJECT_DEVICE_BUILD_CAPABILITIES_H
#define __PROJECT_DEVICE_BUILD_CAPABILITIES_H

{AUTOGEN_C_COMMENT}
#define SILVERSTAR_PROJECT_DEVICE_CAPABILITIES 1U
{rows}

#endif /* __PROJECT_DEVICE_BUILD_CAPABILITIES_H */
"""


def _AlignmentFloat_Render(value: float) -> str:
    literal = f"{value:.9g}"
    if "." not in literal and "e" not in literal:
        literal += ".0"
    return literal + "F"


def _AlignmentDefinitions_Get(model: ProjectModel) -> tuple[tuple[str, str], ...]:
    kind_symbols = {
        "gravity": "ALIGNMENT_CONSTRAINT_GRAVITY",
        "magnetic_field": "ALIGNMENT_CONSTRAINT_MAGNETIC_FIELD",
        "reference_direction": "ALIGNMENT_CONSTRAINT_REFERENCE_DIRECTION",
    }
    axes = {"+X": 1, "-X": -1, "+Y": 2, "-Y": -2, "+Z": 3, "-Z": -3}
    rows = [
        "{ " + ", ".join((
            kind_symbols[item.kind],
            _AlignmentFloat_Render(item.weight),
            _AlignmentFloat_Render(item.declination_deg),
            str(axes[item.body_axis]),
            _AlignmentFloat_Render(item.nav_azimuth_deg),
        )) + " }"
        for item in model.alignment.constraints
    ]
    known_azimuth = model.alignment.external_known_azimuth_deg
    known_yaw = 0.0 if known_azimuth is None else 90.0 - known_azimuth
    return (
        ("SYSTEM_ALIGNMENT_CONSTRAINT_COUNT", f"{len(rows)}U"),
        ("SYSTEM_ALIGNMENT_CONSTRAINTS_INITIALIZER", "{ " + ", ".join(rows) + " }"),
        ("SYSTEM_ALIGNMENT_EXTERNAL_YAW_AUTHORITATIVE", "1U" if model.alignment.external_yaw_authoritative else "0U"),
        ("SYSTEM_ALIGNMENT_USES_MAGNETIC_CONSTRAINT", "1U" if any(item.kind == "magnetic_field" for item in model.alignment.constraints) else "0U"),
        ("SYSTEM_ALIGNMENT_KNOWN_YAW_DEG", _AlignmentFloat_Render(known_yaw)),
    )


