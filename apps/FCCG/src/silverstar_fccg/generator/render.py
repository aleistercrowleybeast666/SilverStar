def _LogContainerVersion_Get(
    model: ProjectModel, catalog: PluginCatalog
) -> str:
    selection = model.protocols.get("logging")
    if selection is None:
        raise ValueError("Decoder generation requires a Logging Protocol")
    contribution = catalog.Component_Get(selection.component).protocol
    matches = [] if contribution is None else [
        profile
        for profile in contribution.profiles.get("logging", ())
        if profile.profile_id == selection.profile
    ]
    if len(matches) != 1:
        raise ValueError(
            "Decoder generation requires exactly one selected logging profile"
        )
    return matches[0].version


def _LogContainerId_Get(
    model: ProjectModel, catalog: PluginCatalog
) -> str:
    selection = model.protocols.get("logging")
    if selection is None:
        raise ValueError("Decoder generation requires a Logging Protocol")
    manifest = catalog.Component_Get(selection.component)
    container = manifest.metadata.get("container_decoder", {})
    if not isinstance(container, dict):
        raise ValueError("Logging Protocol container decoder metadata is invalid")
    container_id = container.get("id")
    if not isinstance(container_id, str) or not container_id:
        raise ValueError("Logging Protocol container decoder id is missing")
    return container_id


def _SupportedPrimitiveTypes_Get(
    schema: dict[str, Any],
) -> tuple[str, ...]:
    records = schema.get("records", ())
    if not isinstance(records, list):
        raise ValueError("Protocol record schema records must be an array")
    primitive_types = {
        field["type"]
        for record in records
        if isinstance(record, dict)
        for fields in (record.get("fields", ()),)
        if isinstance(fields, list)
        for field in fields
        if isinstance(field, dict) and isinstance(field.get("type"), str)
    }
    if not primitive_types:
        raise ValueError("Protocol record schema declares no primitive types")
    return tuple(sorted(primitive_types))


def _LogPhysicalDevices_Get(
    model: ProjectModel,
    catalog: PluginCatalog,
    descriptor_entries: list[dict[str, Any]],
    physical_device_ids: dict[str, int],
) -> list[dict[str, Any]]:
    devices: list[dict[str, Any]] = []
    for instance in model.device_instances:
        manifest = catalog.InstanceComponent_Get(instance)
