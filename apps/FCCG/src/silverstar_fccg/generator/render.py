def _PlatformResources_Render(model: ProjectModel, catalog: PluginCatalog) -> str:
    manifest = catalog.Component_Get(model.mcu)
    contract = manifest.platform
    if contract is None:
        raise ValueError(
            f"Selected MCU has no Platform resource contract: {model.mcu}"
        )
    resolution = ResourceAssignments_Resolve(model, catalog, auto_assign=False)
    active_resource_ids = {
        assignment.provision.resource_id for assignment in resolution.assignments
    }
    if model.hardware.mode == "custom":
        collections = _CustomPlatformResources_Get(model, active_resource_ids)
    else:
        board = catalog.Component_Get(model.board)
        collections = _BoardPlatformResources_Get(
            board, active_resource_ids
        )
        _BoardPlatformResourceClosure_Validate(
            board, resolution.assignments, collections, contract.resource_bindings
        )
    raw_capacities = manifest.metadata.get("resource_capacities", {})
    if not isinstance(raw_capacities, dict):
        raise ValueError("Platform resource_capacities must be an object")
    for collection, entries in collections.items():
        capacity = raw_capacities.get(collection)
        if capacity is None:
            continue
        if not isinstance(capacity, int) or isinstance(capacity, bool) or capacity <= 0:
            raise ValueError(
                f"Platform resource capacity is invalid: {collection}"
            )
        for fallback_index, entry in enumerate(entries):
            logical_index = _PlatformLogicalIndex_Get(entry, fallback_index)
            if (
                not isinstance(logical_index, int)
                or isinstance(logical_index, bool)
                or logical_index < 0
                or logical_index >= capacity
            ):
                raise ValueError(
                    f"Platform resource {collection} exceeds capacity {capacity}"
                )
    includes: set[str] = set()
    sections: list[str] = []
    for kind, binding in contract.resource_bindings.items():
        entries = collections.get(binding.collection, [])
        if not entries:
            continue
        includes.add(binding.include_header)
        sections.append(_PlatformBinding_Render(binding, entries))
    include_text = "\n".join(
        f'#include "{header}"' for header in sorted(includes)
    )
    body = "\n\n".join(sections)
    return f"""#include "{contract.resource_header}"

{AUTOGEN_C_COMMENT}

#include <stddef.h>

{include_text}

{body}
"""


def _CIdentifier_Require(value: Any, field_name: str) -> str:
    if not isinstance(value, str) or re.fullmatch(
        r"[A-Za-z_][A-Za-z0-9_]*", value
    ) is None:
        raise ValueError(f"Platform resource {field_name} is not a safe C identifier")
    return value


def _PlatformLogicalIndex_Get(entry: dict[str, Any], fallback_index: int) -> Any:
    if entry.get("binding_origin") == VERIFIED_BOARD_BINDING_ORIGIN:
        return entry.get("fixed_logical_index")
    return entry.get("logical_index", fallback_index)


def _PlatformEntryResolvedSymbol_Get(entry: dict[str, Any]) -> str:
    port = entry.get("port")
    pin = entry.get("pin")
    if isinstance(port, str) and port and isinstance(pin, str) and pin:
        return f"{port}/{pin}"
    handle = entry.get("handle")
    channel = entry.get("channel_token")
    if isinstance(handle, str) and handle:
        return (
            f"{handle}/{channel}"
            if isinstance(channel, str) and channel
            else handle
        )
    return str(entry.get("physical_alias", "<unresolved>"))


def _BoardPlatformResourceClosure_Validate(
    board: PluginManifest,
    assignments: tuple[Any, ...],
    collections: dict[str, list[dict[str, Any]]],
    bindings: dict[str, Any],
) -> None:
    if board.board is None or not board.board.verified:
        return
    entries_by_id: dict[str, dict[str, Any]] = {}
    for entries in collections.values():
        for entry in entries:
            resource_id = entry.get("id")
            if not isinstance(resource_id, str) or not resource_id:
                continue
            if resource_id in entries_by_id:
                raise ValueError(
                    "Platform Resource Closure Check failed: "
                    f"duplicate logical ID {resource_id}, Board plugin "
                    f"{board.component_id}"
                )
            entries_by_id[resource_id] = entry
    binding_kinds = set(bindings)
    for assignment in assignments:
        provision = assignment.provision
        metadata = provision.metadata
        if metadata.get("binding_origin") != VERIFIED_BOARD_BINDING_ORIGIN:
            continue
        platform_kind = (
            "gpio" if provision.kind.startswith("gpio_") else provision.kind
        )
        if platform_kind not in binding_kinds:
            continue
        logical_id = provision.resource_id
        expected_alias = str(metadata.get("physical_alias", ""))
        entry = entries_by_id.get(logical_id)
        actual_symbol = (
            _PlatformEntryResolvedSymbol_Get(entry)
            if entry is not None
            else "<missing table entry>"
        )
        expected_symbol = _PlatformEntryResolvedSymbol_Get(metadata)
        if (
            entry is None
            or entry.get("c_id") != logical_id
            or entry.get("physical_alias") != expected_alias
            or actual_symbol != expected_symbol
        ):
            raise ValueError(
                "Platform Resource Closure Check failed: "
                f"logical ID {logical_id}, expected alias {expected_alias}, "
                f"actual symbol {actual_symbol}, Board plugin "
                f"{board.component_id}"
            )


def _PlatformBinding_Render(binding, entries: list[dict[str, Any]]) -> str:
    values: list[str] = []
    valid_values: list[str] = []
    declarations: list[str] = []
    for entry in entries:
        logical_index = entry.get("logical_index")
        if entry.get("binding_origin") == VERIFIED_BOARD_BINDING_ORIGIN:
            designator = _CIdentifier_Require(entry.get("c_id"), "c_id")
        elif isinstance(logical_index, int) and 0 <= logical_index <= 0xFFFF:
            designator = f"{logical_index}U"
        else:
            designator = _CIdentifier_Require(entry.get("c_id"), "c_id")
        if binding.entry_kind == "handle":
            handle = _CIdentifier_Require(entry.get("handle"), "handle")
            initializer = f"&{handle}"
        elif binding.entry_kind == "gpio":
            port = _CIdentifier_Require(entry.get("port"), "GPIO port")
            pin = _CIdentifier_Require(entry.get("pin"), "GPIO pin")
            irq_enabled = int(
                bool(entry.get("irq_enabled", entry.get("active_high", 0)))
            )
            initializer = f"{{{port}, {pin}, {irq_enabled}U}}"
        elif binding.entry_kind == "pwm":
            handle = _CIdentifier_Require(entry.get("handle"), "PWM handle")
            channel = _CIdentifier_Require(
                entry.get("channel_token"), "PWM channel"
            )
            pwm_mode = {
                "pwm1": "PLATFORM_PWM_MODE_1",
                "pwm2": "PLATFORM_PWM_MODE_2",
            }.get(str(entry.get("pwm_mode", "")).casefold())
            if pwm_mode is None:
                raise ValueError(
                    "PWM resource has no supported CubeMX PWM1/PWM2 mode"
                )
            numeric_fields = (
                int(entry.get("frequency_hz", 0)),
                int(entry.get("resolution_bits", 0)),
                int(bool(entry.get("active_high", 1))),
            )
            if any(value < 0 or value > 0xFFFFFFFF for value in numeric_fields):
                raise ValueError("PWM resource metadata is out of range")
            initializer = (
                f"{{&{handle}, {channel}, {numeric_fields[0]}U, "
                f"{numeric_fields[1]}U, {pwm_mode}, "
                f"{numeric_fields[2]}U}}"
            )
        elif binding.entry_kind == "timebase":
            handle = _CIdentifier_Require(entry.get("handle"), "Timebase handle")
            handle_type = _CIdentifier_Require(
                entry.get("handle_type"), "Timebase handle type"
            )
            declaration = f"extern {handle_type} {handle};"
            if declaration not in declarations:
                declarations.append(declaration)
            numeric_fields = (
                int(entry.get("counter_frequency_hz", 0)),
                int(entry.get("period_counts", 0)),
                int(entry.get("tick_frequency_hz", 0)),
            )
            if any(value <= 0 or value > 0xFFFFFFFF for value in numeric_fields):
                raise ValueError("Timebase resource metadata is out of range")
            initializer = (
                f"{{&{handle}, {numeric_fields[0]}U, {numeric_fields[1]}U, "
                f"{numeric_fields[2]}U}}"
            )
        elif binding.entry_kind == "systick":
            frequency = int(entry.get("tick_frequency_hz", 0))
            if frequency != 1_000:
                raise ValueError("SysTick resource must have a verified 1 kHz HAL tick")
            initializer = f"{{{frequency}U}}"
        else:
            raise ValueError(
                f"Unsupported Platform resource entry kind: {binding.entry_kind}"
            )
        values.append(f"    [{designator}] = {initializer}")
        valid_values.append(f"    [{designator}] = 1U")
    initializer_text = ",\n".join(values)
    if binding.entry_kind == "handle":
        return f"""static void * const {binding.table_symbol}[{binding.count_symbol}] =
{{
{initializer_text}
}};

void *{binding.getter}({binding.id_type} id)
{{
    return ((uint32_t)id < (uint32_t){binding.count_symbol}) ?
        {binding.table_symbol}[id] : NULL;
}}"""
    declaration_text = "\n".join(declarations)
    declaration_block = f"{declaration_text}\n\n" if declaration_text else ""
    validity_text = ",\n".join(valid_values)
    validity_symbol = f"{binding.table_symbol}_valid"
    return f"""{declaration_block}static const {binding.struct_type}
    {binding.table_symbol}[{binding.count_symbol}] =
{{
{initializer_text}
}};

static const uint8_t {validity_symbol}[{binding.count_symbol}] =
{{
{validity_text}
}};

uint8_t {binding.getter}(
    {binding.id_type} id,
    {binding.struct_type} *resource)
{{
    if (((uint32_t)id >= (uint32_t){binding.count_symbol}) ||
        ({validity_symbol}[id] == 0U) ||
        (resource == NULL))
    {{
        return 0U;
    }}
    *resource = {binding.table_symbol}[id];
    return 1U;
}}"""


def _CustomPlatformResources_Get(
    model: ProjectModel, active_resource_ids: set[str]
) -> dict[str, list[dict[str, Any]]]:
    platform: dict[str, list[dict[str, Any]]] = {
        "uarts": [],
        "spis": [],
        "adcs": [],
        "gpios": [],
        "i2cs": [],
        "cans": [],
        "pwms": [],
        "timebases": [],
    }
    destinations = {
        "uart": "uarts",
        "spi": "spis",
        "adc": "adcs",
        "i2c": "i2cs",
        "can_classic": "cans",
        "pwm": "pwms",
        "time": "timebases",
    }
    for resource in model.hardware.resources:
        metadata = resource.metadata
        destination = destinations.get(resource.kind)
        if (
            resource.kind in {"i2c", "can_classic", "pwm", "time"}
            and resource.resource_id not in active_resource_ids
        ):
            continue
        if destination is not None and isinstance(metadata.get("handle"), str):
            entry = {"id": resource.resource_id, **metadata}
            entry.pop("binding_origin", None)
            entry.pop("fixed_logical_index", None)
            platform[destination].append(entry)
        elif resource.kind.startswith("gpio_") and isinstance(metadata.get("port"), str):
            entry = {"id": resource.resource_id, **metadata}
            entry.pop("binding_origin", None)
            entry.pop("fixed_logical_index", None)
            platform["gpios"].append(entry)
    for values in platform.values():
        values.sort(key=lambda entry: int(entry.get("logical_index", 0)))
    return platform


def _BoardPlatformResources_Get(
    board, active_resource_ids: set[str]
) -> dict[str, list[dict[str, Any]]]:
    if board.board is not None and not board.board.ioc_file:
        legacy = board.metadata.get("platform_resources")
        if isinstance(legacy, dict):
            provisions = {
                provision.resource_id: provision
                for provision in board.resource_provisions
            }
            normalized: dict[str, list[dict[str, Any]]] = {}
            for collection, entries in legacy.items():
                if not isinstance(collection, str) or not isinstance(entries, list):
                    raise ValueError("Legacy Board platform_resources is invalid")
                normalized_entries: list[dict[str, Any]] = []
                for entry in entries:
                    if not isinstance(entry, dict):
                        raise ValueError("Legacy Board platform resource is invalid")
                    resource_id = entry.get("id")
                    if not isinstance(resource_id, str) or not resource_id:
                        raise ValueError("Legacy Board platform resource has no id")
                    normalized_entry = dict(entry)
                    provision = provisions.get(resource_id)
                    if provision is not None and "c_id" not in normalized_entry:
                        normalized_entry["c_id"] = provision.metadata.get("c_id")
                    normalized_entries.append(normalized_entry)
                normalized[collection] = normalized_entries
            return normalized
    platform: dict[str, list[dict[str, Any]]] = {
        "uarts": [],
        "spis": [],
        "adcs": [],
        "gpios": [],
        "i2cs": [],
        "cans": [],
        "pwms": [],
        "timebases": [],
    }
    destinations = {
        "uart": "uarts",
        "spi": "spis",
        "adc": "adcs",
        "i2c": "i2cs",
        "can_classic": "cans",
        "pwm": "pwms",
        "time": "timebases",
    }
    for provision in BoardResourceProvisions_Get(board):
        metadata = provision.metadata
        destination = destinations.get(provision.kind)
        if (
            provision.kind in {"i2c", "can_classic", "pwm", "time"}
            and provision.resource_id not in active_resource_ids
        ):
            continue
        if destination is not None and isinstance(metadata.get("handle"), str):
            platform[destination].append(
                {"id": provision.resource_id, **metadata}
            )
        elif provision.kind.startswith("gpio_") and isinstance(
            metadata.get("port"), str
        ):
            platform["gpios"].append(
                {"id": provision.resource_id, **metadata}
            )
    for values in platform.values():
        values.sort(
            key=lambda entry: (
                int(entry.get("fixed_logical_index", 0)),
                str(entry.get("c_id", "")),
            )
        )
    return platform


