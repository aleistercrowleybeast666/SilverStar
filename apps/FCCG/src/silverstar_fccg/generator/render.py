def _DescriptorSymbol_Get(device_class: str, instance_id: int) -> str:
    token = device_class.removeprefix("SYSTEM_DEVICE_CLASS_")
    aliases = {
        "BAROMETER": "BARO",
        "HARDWARE_QUATERNION": "ATTITUDE",
        "MAGNETOMETER": "MAG",
        "MISSION_ACTION": "ACTION",
    }
    token = aliases.get(token, token)
    if re.fullmatch(r"[A-Z][A-Z0-9_]*", token) is None:
        raise ValueError(f"Invalid device descriptor class token: {device_class}")
    return f"PROJECT_DESCRIPTOR_ID_{token}_{instance_id}"


def _DeviceDescriptorEntries_Get(
    model: ProjectModel, catalog: PluginCatalog
) -> list[dict[str, Any]]:
    catalog = catalog.ProjectView_Get(model)
    selected_instances: dict[str, list[str]] = {}
    for instance in model.device_instances:
        selected_instances.setdefault(instance.plugin, []).append(instance.instance_id)
    entries: list[dict[str, Any]] = []
    for component_id in model.ComponentIds_Get():
        manifest = catalog.Component_Get(component_id)
        raw_entries = manifest.metadata.get("device_descriptors", [])
        if not isinstance(raw_entries, list):
            raise ValueError(
                f"Component {component_id} device_descriptors must be an array"
            )
        instance_ids: tuple[str, ...] = ("",)
        if manifest.component_type == "device":
            instance_ids = tuple(selected_instances.get(component_id, ()))
        for source_instance_id in instance_ids:
            instance_manifest = (
                catalog.InstanceIdComponent_Get(source_instance_id)
                if source_instance_id else manifest
            )
            raw_entries = instance_manifest.metadata.get("device_descriptors", [])
            if source_instance_id and instance_manifest.instance_resource_binding is not None:
                accessor = instance_manifest.instance_resource_binding.accessor
                source_instance_index = sum(
                    1 for previous in instance_ids[:instance_ids.index(source_instance_id)]
                    if catalog.InstanceIdComponent_Get(previous).instance_resource_binding
                    is not None
                    and catalog.InstanceIdComponent_Get(
                        previous
                    ).instance_resource_binding.accessor == accessor
                )
            else:
                source_instance_index = (
                    instance_ids.index(source_instance_id) if source_instance_id else 0
                )
            for raw_entry in raw_entries:
                if not isinstance(raw_entry, dict):
                    raise ValueError(
                        f"Component {component_id} device descriptor is invalid"
                    )
                entry = dict(raw_entry)
                entry["_component_id"] = component_id
                entry["_source_instance_id"] = source_instance_id
                entry["_source_instance_index"] = source_instance_index
                physical_symbol = str(entry.get("physical_device_id", ""))
                if len(instance_ids) > 1 and instance_ids.index(source_instance_id) > 0:
                    physical_symbol = (
                        f"{physical_symbol}_{instance_ids.index(source_instance_id)}"
                    )
                entry["physical_device_id"] = physical_symbol
                entries.append(entry)
    entries.sort(
        key=lambda entry: (
            int(entry.get("order", 0)),
            str(entry["_component_id"]),
            str(entry["_source_instance_id"]),
            str(entry.get("class", "")),
        )
    )
    used_instances: dict[str, set[int]] = {}
    for descriptor_id, entry in enumerate(entries, start=1):
        device_class = str(entry.get("class", ""))
        used = used_instances.setdefault(device_class, set())
        requested = entry.get("instance")
        if isinstance(requested, int) and requested >= 0 and requested not in used:
            instance_id = requested
        else:
            instance_id = 0
            while instance_id in used:
                instance_id += 1
        if instance_id > 255:
            raise ValueError(f"Too many instances for device class {device_class}")
        used.add(instance_id)
        physical_id = str(entry.get("physical_device_id", ""))
        if re.fullmatch(
            r"PROJECT_PHYSICAL_DEVICE_ID_[A-Z0-9_]+", physical_id
        ) is None:
            raise ValueError(
                f"Component {entry['_component_id']} has an invalid physical device id"
            )
        entry["_descriptor_id"] = descriptor_id
        entry["_instance_id"] = instance_id
        entry["_descriptor_symbol"] = _DescriptorSymbol_Get(
            device_class, instance_id
        )
    primary_by_class: dict[str, str] = {}
    resolution = CapabilityResolution_Resolve(model, catalog)
    for route in resolution.routes:
        device_class = _CapabilityDeviceClass_Get(route.requirement.capability)
        if device_class and device_class not in primary_by_class:
            primary_by_class[device_class] = route.provider.instance_id
    entries_by_class: dict[str, list[dict[str, Any]]] = {}
    for entry in entries:
        entries_by_class.setdefault(str(entry.get("class", "")), []).append(entry)
    for device_class, class_entries in entries_by_class.items():
        if len(class_entries) <= 1:
            continue
        primary_instance = primary_by_class.get(
            device_class, str(class_entries[0].get("_source_instance_id", ""))
        )
        for entry in class_entries:
            flag_tokens = [
                token.strip()
                for token in str(entry.get("flags", "0U")).split("|")
                if token.strip()
                and token.strip() != "SYSTEM_DESCRIPTOR_FLAG_PRIMARY"
            ]
            if str(entry.get("_source_instance_id", "")) == primary_instance:
                flag_tokens.append("SYSTEM_DESCRIPTOR_FLAG_PRIMARY")
            entry["flags"] = " | ".join(flag_tokens) if flag_tokens else "0U"
    return entries


def _PhysicalDeviceDefinitions_Get(
    catalog: PluginCatalog,
    descriptor_entries: list[dict[str, Any]] | None = None,
) -> tuple[tuple[str, int], ...]:
    orders: dict[str, int] = {"PROJECT_PHYSICAL_DEVICE_ID_NONE": -1}
    for manifest in catalog.All_Get():
        entries = manifest.metadata.get("device_descriptors", [])
        if not isinstance(entries, list):
            continue
        for entry in entries:
            if not isinstance(entry, dict):
                continue
            symbol = entry.get("physical_device_id")
            if not isinstance(symbol, str) or re.fullmatch(
                r"PROJECT_PHYSICAL_DEVICE_ID_[A-Z0-9_]+", symbol
            ) is None:
                continue
            orders[symbol] = min(orders.get(symbol, 0x7FFFFFFF), int(entry.get("order", 0)))
    for entry in descriptor_entries or ():
        symbol = entry.get("physical_device_id")
        if not isinstance(symbol, str) or re.fullmatch(
            r"PROJECT_PHYSICAL_DEVICE_ID_[A-Z0-9_]+", symbol
        ) is None:
            raise ValueError("Generated physical-device symbol is invalid")
        orders.setdefault(symbol, 0x40000000 + int(entry["_descriptor_id"]))
    symbols = sorted(
        orders,
        key=lambda symbol: (
            0 if symbol == "PROJECT_PHYSICAL_DEVICE_ID_NONE" else 1,
            orders[symbol],
            symbol,
        ),
    )
    return tuple((symbol, value) for value, symbol in enumerate(symbols))


def _DeviceInstancesHeader_Render(
    model: ProjectModel, catalog: PluginCatalog
) -> str:
    core = catalog.Component_Get(model.core)
    template_path = (
        core.package_root
        / "templates"
        / "generated"
        / "project_device_instances.h"
    )
    if not template_path.is_file():
        raise ValueError("Core plugin has no generated device-instance facade header")
    template = template_path.read_text(encoding="utf-8")
    start_marker = "#define PROJECT_PHYSICAL_DEVICE_ID_NONE"
    end_marker = "uint8_t ProjectDeviceInstance_CountGet"
    start = template.find(start_marker)
    end = template.find(end_marker, start)
    if start < 0 or end < 0:
        raise ValueError("Device-instance facade header template markers changed")
    descriptors = _DeviceDescriptorEntries_Get(model, catalog)
    physical_definitions = _PhysicalDeviceDefinitions_Get(catalog, descriptors)
    physical_width = max(len(symbol) for symbol, _value in physical_definitions)
    physical_rows = "\n".join(
        f"#define {symbol:<{physical_width}} {value}U"
        for symbol, value in physical_definitions
    )
    descriptor_width = max(
        (len(str(entry["_descriptor_symbol"])) for entry in descriptors),
        default=1,
    )
    descriptor_rows = "\n".join(
        f"#define {entry['_descriptor_symbol']:<{descriptor_width}} "
        f"{entry['_descriptor_id']}U"
        for entry in descriptors
    )
    selected_counts: dict[str, int] = {}
    for entry in descriptors:
        device_class = str(entry["class"])
        selected_counts[device_class] = selected_counts.get(device_class, 0) + 1
    bound_values: list[tuple[str, int]] = []
    for device_class, (_label, bound_macro) in _DEVICE_FACADE_CLASSES.items():
        selected_count = selected_counts.get(device_class, 0)
        pattern = rf"#define\s+{re.escape(bound_macro)}\s+(\d+)U"
        match = re.search(pattern, template)
        if match is None:
            raise ValueError(
                f"Device-instance facade bound is missing: {bound_macro}"
            )
        bound_values.append((bound_macro, max(int(match.group(1)), selected_count)))
    bound_width = max(len(macro) for macro, _value in bound_values)
    bound_rows = "\n".join(
        f"#define {macro:<{bound_width}} {value}U"
        for macro, value in bound_values
    )
    replacement = (
        physical_rows
        + "\n\n"
        + descriptor_rows
        + "\n\n"
        + "/* Static bounds for per-capability runtime state. */\n"
        + bound_rows
        + "\n\n"
    )
    rendered = template[:start] + replacement + template[end:]
    return rendered.replace(
        "#define __PROJECT_DEVICE_INSTANCES_H\n",
        "#define __PROJECT_DEVICE_INSTANCES_H\n\n" + AUTOGEN_C_COMMENT + "\n",
        1,
    )


