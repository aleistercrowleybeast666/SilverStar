def _DeviceInstanceSwitches_Render(
    template: str, model: ProjectModel, catalog: PluginCatalog
) -> str:
    descriptors = _DeviceDescriptorEntries_Get(model, catalog)
    endpoints: dict[str, list[tuple[dict[str, Any], dict[str, Any]]]] = {
        device_class: [] for device_class in _DEVICE_FACADE_CLASSES
    }
    headers: set[str] = set()
    for entry in descriptors:
        device_class = str(entry.get("class", ""))
        if device_class not in endpoints:
            continue
        source_id = str(entry["_source_instance_id"])
        manifest = (
            catalog.InstanceIdComponent_Get(source_id)
            if source_id else catalog.Component_Get(str(entry["_component_id"]))
        )
        bindings = manifest.metadata.get("device_instance_bindings")
        binding = bindings.get(device_class) if isinstance(bindings, dict) else None
        if not isinstance(binding, dict):
            raise ValueError(
                f"Device plugin {manifest.component_id} has no direct binding "
                f"for {device_class}"
            )
        allowed = {
            "function_prefix",
            "headers",
            "operations",
            "pass_instance",
            "unsupported_operations",
        }
        if not set(binding).issubset(allowed):
            raise ValueError(
                f"Device plugin {manifest.component_id} direct binding has "
                "unknown fields"
            )
        prefix = binding.get("function_prefix")
        if not isinstance(prefix, str) or re.fullmatch(
            r"[A-Za-z_][A-Za-z0-9_]*", prefix
        ) is None:
            raise ValueError(
                f"Device plugin {manifest.component_id} direct binding prefix "
                "is invalid"
            )
        raw_headers = binding.get("headers", [])
        if not isinstance(raw_headers, list) or not all(
            isinstance(header, str)
            and re.fullmatch(r"[A-Za-z0-9_./-]+\.h", header)
            for header in raw_headers
        ):
            raise ValueError(
                f"Device plugin {manifest.component_id} direct binding headers "
                "are invalid"
            )
        headers.update(raw_headers)
        endpoints[device_class].append((entry, binding))
    rendered = template
    for device_class, (label, _bound_macro) in _DEVICE_FACADE_CLASSES.items():
        class_endpoints = sorted(
            endpoints[device_class], key=lambda item: int(item[0]["_instance_id"])
        )
        actual_ids = [int(entry["_instance_id"]) for entry, _binding in class_endpoints]
        if actual_ids != list(range(len(actual_ids))):
            raise ValueError(
                f"Generated {device_class} endpoints are not contiguous"
            )
        function_pattern = re.compile(
            rf"SystemDeviceResult Project{label}Instance_([A-Za-z0-9_]+)\("
        )
        operations = tuple(
            match.group(1) for match in function_pattern.finditer(rendered)
        )
        if not operations:
            raise ValueError(f"Device-instance facade class is missing: {label}")
        for operation in operations:
            rendered = _DeviceInstanceFunctionSwitch_Render(
                rendered, label, operation, class_endpoints
            )
    if headers:
        anchor = '#include "silverstar_assert.h"\n'
        if anchor not in rendered:
            raise ValueError("Device-instance facade include anchor changed")
        additions = "".join(f'#include "{header}"\n' for header in sorted(headers))
        rendered = rendered.replace(anchor, anchor + additions, 1)
    return rendered


def _DeviceInstanceFunctionSwitch_Render(
    source: str,
    label: str,
    operation: str,
    endpoints: list[tuple[dict[str, Any], dict[str, Any]]],
) -> str:
    function_marker = f"SystemDeviceResult Project{label}Instance_{operation}("
    function_start = source.find(function_marker)
    if function_start < 0:
        raise ValueError(f"Device-instance facade function is missing: {function_marker}")
    switch_start = source.find("switch (instance_id)", function_start)
    next_function = source.find("\nSystemDeviceResult ", function_start + 1)
    if switch_start < 0 or (next_function >= 0 and switch_start > next_function):
        raise ValueError(f"Device-instance facade switch is missing: {function_marker}")
    brace_start = source.find("{", switch_start)
    brace_end = _CBlockEnd_Find(source, brace_start)
    original = source[brace_start + 1 : brace_end]
    argument_match = re.search(
        r"case\s+0U:\s*return\s+[A-Za-z_][A-Za-z0-9_]*\((.*?)\);",
        original,
        re.DOTALL,
    )
    if argument_match is None:
        raise ValueError(
            f"Device-instance facade reference case changed: {function_marker}"
        )
    arguments = " ".join(argument_match.group(1).split())
    cases: list[str] = []
    for entry, binding in endpoints:
        unsupported = binding.get("unsupported_operations", [])
        if not isinstance(unsupported, list) or not all(
            isinstance(value, str) for value in unsupported
        ):
            raise ValueError("Device-instance unsupported operation list is invalid")
        instance_id = int(entry["_instance_id"])
        if operation in unsupported:
            cases.append(
                f"        case {instance_id}U: return SYSTEM_DEVICE_UNSUPPORTED;"
            )
            continue
        overrides = binding.get("operations", {})
        if not isinstance(overrides, dict) or not all(
            isinstance(key, str) and isinstance(value, str)
            for key, value in overrides.items()
        ):
            raise ValueError("Device-instance operation overrides are invalid")
        symbol = overrides.get(
            operation, f"{binding['function_prefix']}_{operation}"
        )
        if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", symbol) is None:
            raise ValueError("Device-instance direct function symbol is invalid")
        pass_instance = binding.get("pass_instance", False)
        if not isinstance(pass_instance, bool):
            raise ValueError("Device-instance pass_instance must be boolean")
        call_arguments = arguments
        if pass_instance:
            source_index = int(entry["_source_instance_index"])
            call_arguments = (
                f"{source_index}U, {arguments}" if arguments else f"{source_index}U"
            )
        cases.append(
            f"        case {instance_id}U: return {symbol}({call_arguments});"
        )
    body = "\n" + "\n".join(cases)
    if cases:
        body += "\n"
    body += "        default: return SYSTEM_DEVICE_NOT_PRESENT;\n    "
    return source[: brace_start + 1] + body + source[brace_end:]


def _CBlockEnd_Find(source: str, brace_start: int) -> int:
    if brace_start < 0 or source[brace_start] != "{":
        raise ValueError("Generated C block start is missing")
    depth = 0
    for index in range(brace_start, len(source)):
        if source[index] == "{":
            depth += 1
        elif source[index] == "}":
            depth -= 1
            if depth == 0:
                return index
    raise ValueError("Generated C block is unterminated")


