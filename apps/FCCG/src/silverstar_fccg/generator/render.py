def _ResourceHeader_Render(model: ProjectModel, catalog: PluginCatalog) -> str:
    catalog = catalog.ProjectView_Get(model)
    result = ResourceAssignments_Resolve(model, catalog)
    if not result.valid:
        raise ValueError("Cannot generate resource header: " + "; ".join(result.errors))
    includes = set()
    values: dict[str, str] = {}
    assigned_macros: set[str] = set()
    instance_plugins = {
        instance.instance_id: catalog.InstanceComponent_Get(instance)
        for instance in model.device_instances
    }
    for assignment in result.assignments:
        owner_manifest = instance_plugins.get(assignment.component_id)
        if (
            owner_manifest is not None
            and owner_manifest.instance_resource_binding is not None
        ):
            continue
        macro = assignment.requirement.binding_macro
        if not macro:
            continue
        header = assignment.provision.metadata.get("header")
        if isinstance(header, str) and header:
            includes.add(header)
        c_id = assignment.provision.metadata.get("c_id", assignment.provision.resource_id)
        if macro in values and values[macro] != c_id:
            raise ValueError(f"Resource binding macro is ambiguous: {macro}")
        values[macro] = str(c_id)
        assigned_macros.add(macro)
    optional_bindings_by_macro: dict[str, object] = {}
    for manifest in catalog.All_Get():
        raw_bindings = manifest.metadata.get("optional_resource_bindings", [])
        if not isinstance(raw_bindings, list):
            raise ValueError(
                f"Component {manifest.component_id} optional_resource_bindings "
                "must be an array"
            )
        for binding in raw_bindings:
            if not isinstance(binding, dict):
                raise ValueError("Component optional resource binding is invalid")
            macro = binding.get("binding_macro")
            if not isinstance(macro, str):
                raise ValueError("Component optional resource binding is invalid")
            previous = optional_bindings_by_macro.setdefault(macro, binding)
            if previous != binding:
                raise ValueError(
                    f"Optional resource binding is ambiguous: {macro}"
                )
    optional_bindings = tuple(optional_bindings_by_macro.values())
    identifier_pattern = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")
    macro_pattern = re.compile(r"[A-Z][A-Z0-9_]*")
    for binding in optional_bindings:
        if not isinstance(binding, dict) or set(binding) != {
            "binding_macro",
            "enabled_macro",
            "fallback",
            "header",
        }:
            raise ValueError("Component optional resource binding is invalid")
        macro = binding.get("binding_macro")
        enabled_macro = binding.get("enabled_macro")
        fallback = binding.get("fallback")
        header = binding.get("header")
        if (
            not isinstance(macro, str)
            or macro_pattern.fullmatch(macro) is None
            or not isinstance(enabled_macro, str)
            or macro_pattern.fullmatch(enabled_macro) is None
            or not isinstance(fallback, str)
            or identifier_pattern.fullmatch(fallback) is None
            or not isinstance(header, str)
            or re.fullmatch(r"[A-Za-z0-9_./-]+\.h", header) is None
            or ".." in Path(header).parts
        ):
            raise ValueError("Component optional resource binding token is unsafe")
        includes.add(header)
        values.setdefault(macro, fallback)
        values[enabled_macro] = "1U" if macro in assigned_macros else "0U"
    include_text = "\n".join(f'#include "{header}"' for header in sorted(includes))
    define_text = "\n".join(
        f"#define {macro:<42} {value}" for macro, value in values.items()
    )
    instance_declarations = _InstanceResourceDeclarations_Render(model, catalog)
    return f"""#ifndef __PROJECT_RESOURCES_H
#define __PROJECT_RESOURCES_H

{AUTOGEN_C_COMMENT}

{include_text}

#include "{catalog.Component_Get(model.mcu).platform.resource_header}"
#include "system_device_types.h"

{define_text}

{instance_declarations}

#endif /* __PROJECT_RESOURCES_H */
"""


def _InstanceBindingGroups_Get(model: ProjectModel, catalog: PluginCatalog):
    groups: dict[str, tuple[PluginManifest, list[DeviceInstance]]] = {}
    for instance in model.device_instances:
        manifest = catalog.InstanceComponent_Get(instance)
        binding = manifest.instance_resource_binding
        if binding is None:
            continue
        if binding.accessor not in groups:
            groups[binding.accessor] = (manifest, [])
        groups[binding.accessor][1].append(instance)
    return tuple(groups[key] for key in sorted(groups))


def _InstanceResourceDeclarations_Render(
    model: ProjectModel, catalog: PluginCatalog
) -> str:
    sections: list[str] = []
    for manifest, instances in _InstanceBindingGroups_Get(model, catalog):
        binding = manifest.instance_resource_binding
        assert binding is not None
        requirement_by_name = {
            requirement.name: requirement
            for requirement in manifest.resource_requirements
        }
        fields = []
        for field in binding.fields:
            requirement = requirement_by_name[field.requirement]
            platform_kind = (
                "gpio" if requirement.kind.startswith("gpio_") else requirement.kind
            )
            platform_binding = catalog.Component_Get(
                model.mcu
            ).platform.resource_bindings.get(platform_kind)
            if platform_binding is None:
                raise ValueError(
                    f"Platform has no typed resource binding for {requirement.kind}"
                )
            fields.append(f"    {platform_binding.id_type} {field.member};")
        sections.append(
            f"#define {binding.count_symbol:<42} {len(instances)}U\n"
            f"#define {binding.count_symbol}_MAX{' ' * max(1, 38 - len(binding.count_symbol))} "
            f"{binding.runtime_context_upper_bound}U\n\n"
            f"typedef struct\n{{\n" + "\n".join(fields) + "\n"
            f"}} {binding.struct_type};\n\n"
            f"SystemDeviceResult {binding.accessor}(\n"
            f"    uint8_t source_instance, {binding.struct_type} *resources);"
        )
    return "\n\n".join(sections)


def _InstanceResourcesSource_Render(
    model: ProjectModel, catalog: PluginCatalog
) -> str:
    catalog = catalog.ProjectView_Get(model)
    resolution = ResourceAssignments_Resolve(model, catalog)
    if not resolution.valid:
        raise ValueError(
            "Cannot generate instance resource tables: "
            + "; ".join(resolution.errors)
        )
    assignments = {
        (assignment.component_id, assignment.requirement.name): assignment
        for assignment in resolution.assignments
    }
    sections: list[str] = []
    resource_value = re.compile(
        r"(?:[A-Za-z_][A-Za-z0-9_]*|"
        r"\(\([A-Za-z_][A-Za-z0-9_]*\)[0-9]+U\))"
    )
    for manifest, instances in _InstanceBindingGroups_Get(model, catalog):
        binding = manifest.instance_resource_binding
        assert binding is not None
        rows: list[str] = []
        for instance in instances:
            values: list[str] = []
            for field in binding.fields:
                assignment = assignments.get((instance.instance_id, field.requirement))
                if assignment is None:
                    raise ValueError(
                        f"Missing instance resource assignment: "
                        f"{instance.instance_id}:{field.requirement}"
                    )
                c_id = str(
                    assignment.provision.metadata.get(
                        "c_id", assignment.provision.resource_id
                    )
                )
                if resource_value.fullmatch(c_id) is None:
                    raise ValueError(
                        f"Instance resource C identifier is unsafe: {c_id}"
                    )
                values.append(f".{field.member} = {c_id}")
            rows.append("    { " + ", ".join(values) + " }")
        table_symbol = f"s_{binding.accessor.removesuffix('_Get')}"
        sections.append(
            f"_Static_assert({binding.count_symbol} <= {binding.count_symbol}_MAX,\n"
            f"    \"{manifest.component_id} instance count exceeds context bound\");\n\n"
            f"static const {binding.struct_type} {table_symbol}[{binding.count_symbol}] =\n"
            "{\n" + ",\n".join(rows) + "\n};\n\n"
            f"SystemDeviceResult {binding.accessor}(\n"
            f"    uint8_t source_instance, {binding.struct_type} *resources)\n"
            "{\n"
            "    if (resources == NULL) { return SYSTEM_DEVICE_INVALID_ARGUMENT; }\n"
            f"    if (source_instance >= {binding.count_symbol})\n"
            "    {\n"
            "        return SYSTEM_DEVICE_NOT_PRESENT;\n"
            "    }\n"
            f"    *resources = {table_symbol}[source_instance];\n"
            "    return SYSTEM_DEVICE_OK;\n"
            "}"
        )
    body = "\n\n".join(sections)
    return f"""#include "project_resources.h"

{AUTOGEN_C_COMMENT}

#include <stddef.h>

{body}
"""


