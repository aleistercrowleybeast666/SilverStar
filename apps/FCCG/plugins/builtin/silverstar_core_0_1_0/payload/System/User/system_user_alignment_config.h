/* Sources selected for this mission's preflight alignment transaction. */
#ifndef SYSTEM_USER_ALIGNMENT_SELECTED_MASK
#define SYSTEM_USER_ALIGNMENT_SELECTED_MASK \
    (SYSTEM_ALIGNMENT_SOURCE_MASK_ATTITUDE | \
     SYSTEM_ALIGNMENT_SOURCE_MASK_GNSS_ORIGIN | \
     SYSTEM_ALIGNMENT_SOURCE_MASK_BARO_ORIGIN)
#endif

/* Selected sources that must be ready before Alignment can become READY. */
#ifndef SYSTEM_USER_ALIGNMENT_REQUIRED_MASK
#define SYSTEM_USER_ALIGNMENT_REQUIRED_MASK \
    (SYSTEM_ALIGNMENT_SOURCE_MASK_ATTITUDE | \
     SYSTEM_ALIGNMENT_SOURCE_MASK_BARO_ORIGIN)
#endif

/* READY validity guard. All thresholds apply before mission START only. */
#define SYSTEM_USER_ALIGNMENT_GUARD_ENABLE                         1U
#define SYSTEM_USER_ALIGNMENT_GUARD_GYRO_THRESHOLD_RADPS        0.05f
#define SYSTEM_USER_ALIGNMENT_GUARD_ACCEL_TOLERANCE_MPS2        0.50f
#define SYSTEM_USER_ALIGNMENT_GUARD_ATTITUDE_DELTA_RAD     0.034906585f
#define SYSTEM_USER_ALIGNMENT_GUARD_CONFIRM_DURATION_US        100000ULL
#define SYSTEM_USER_ALIGNMENT_GUARD_SAMPLE_FRESHNESS_US        100000ULL

#if ((SYSTEM_USER_ALIGNMENT_REQUIRED_MASK & \
      ~SYSTEM_USER_ALIGNMENT_SELECTED_MASK) != 0U)
#error "Alignment required sources must be a subset of selected sources"
#endif

#if ((SYSTEM_USER_ALIGNMENT_SELECTED_MASK & \
      ~SYSTEM_ALIGNMENT_SOURCE_MASK_DEFINED) != 0U)
#error "Alignment selected mask contains an undefined source"
#endif

#if (SYSTEM_ALIGNMENT_WINDOW_MIN_SAMPLES == 0U) || \
    (SYSTEM_ALIGNMENT_WINDOW_MAX_SAMPLES < \
     SYSTEM_ALIGNMENT_WINDOW_MIN_SAMPLES) || \
    (SYSTEM_ALIGNMENT_WINDOW_MAX_SAMPLES > 128U)
#error "Alignment floating-window sample limits are invalid"
#endif

#endif /* __SYSTEM_USER_ALIGNMENT_CONFIG_H */
