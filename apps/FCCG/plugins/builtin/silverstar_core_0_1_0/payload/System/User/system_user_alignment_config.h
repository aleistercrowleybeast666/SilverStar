/* Shared non-blocking static window. */
#define SYSTEM_ALIGNMENT_WINDOW_MIN_SAMPLES             100U
#define SYSTEM_ALIGNMENT_WINDOW_MAX_SAMPLES             128U
#define SYSTEM_ALIGNMENT_WINDOW_MIN_DURATION_US       500000ULL
#define SYSTEM_ALIGNMENT_WINDOW_MAX_GAP_US             50000ULL
