#define SYSTEM_ALIGNMENT_MAG_MIN_UT                       10.0f
#define SYSTEM_ALIGNMENT_MAG_MAX_UT                      100.0f
#define SYSTEM_ALIGNMENT_MAG_MAX_MAGNITUDE_DEVIATION_RATIO 0.20f
